// Bundles the game into a single self-contained HTML file.
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync, cpSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';

const res = await build({ entryPoints: ['src/main.ts'], bundle: true, minify: !process.env.NOMIN, write: false, format: 'iife', target: 'es2020', legalComments: 'none' });
const js = res.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const css = readFileSync('src/styles.css', 'utf8');
// Fonts: Cormorant SC (titles) and EB Garamond (text). The standalone game ships them in fonts/ so the first launch
// offline shows the right type; the artifact page may not carry files, so it takes the same two families from Google.
const fonts = '<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin><link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Cormorant+SC:wght@500;600;700&family=EB+Garamond:ital,wght@0,400;0,600;0,700;1,400&display=swap">';
const fontFaces = readFileSync('fonts/fonts.css', 'utf8').replace(/\/\*[\s\S]*?\*\//, '').trim();
const fontFiles = readdirSync('fonts').filter(f => f.endsWith('.woff2'));
const bodyHtml = `<div id="app"></div>\n<script>${js}</script>`;

// Artifact page (the host adds the doctype/head skeleton).
const artifact = `<title>Lasting Empires</title>\n${fonts}\n<style>${css}</style>\n${bodyHtml}\n`;
// Standalone page for local play or GitHub Pages.
// Installable app (PWA): manifest, icons and an offline service worker. Registered only when served over https.
const pwaHead = '<link rel="manifest" href="manifest.webmanifest"><link rel="apple-touch-icon" href="icons/icon-180.png"><link rel="icon" href="icons/icon-192.png"><meta name="mobile-web-app-capable" content="yes"><meta name="apple-mobile-web-app-status-bar-style" content="default"><meta name="apple-mobile-web-app-title" content="Empires">';
const swReg = "<script>if('serviceWorker' in navigator && (location.protocol==='https:'||location.hostname==='localhost'))navigator.serviceWorker.register('sw.js')</script>";
const standalone = `<!doctype html>\n<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover"><meta name="theme-color" content="#efe8d6"><meta name="apple-mobile-web-app-capable" content="yes"><title>Lasting Empires</title>${pwaHead}<style>${fontFaces}:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px);box-sizing:border-box}[hidden]{display:none!important}${css}</style></head><body>${bodyHtml}${swReg}</body></html>\n`;
const version = createHash('sha1').update(standalone).digest('hex').slice(0, 10);
const sw = `// Generated by scripts/build.mjs. Keeps the game playable offline.
const CACHE = 'empires-${version}';
const CORE = ['./', 'index.html', 'manifest.webmanifest', 'icons/icon-192.png', 'icons/icon-512.png', 'icons/icon-180.png', 'icons/maskable-512.png', ${fontFiles.map(f => `'fonts/${f}'`).join(', ')}];
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(CORE)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  // the page: network first so updates arrive, cache when offline
  if (req.mode === 'navigate') { e.respondWith(fetch(req).then(r => { const c = r.clone(); caches.open(CACHE).then(x => x.put('index.html', c)); return r; }).catch(() => caches.match('index.html'))); return; }
  // fonts and our own files: cache first, fill on the way
  if (url.origin === location.origin || url.host.endsWith('gstatic.com') || url.host.endsWith('googleapis.com')) {
    e.respondWith(caches.match(req).then(hit => hit || fetch(req).then(r => { if (r.ok || r.type === 'opaque') { const c = r.clone(); caches.open(CACHE).then(x => x.put(req, c)); } return r; })));
  }
});
`;
mkdirSync('dist', { recursive: true });
writeFileSync('dist/lasting-empires.html', artifact);
writeFileSync('dist/index.html', standalone);
cpSync('art', 'dist/art', { recursive: true }); // card paintings, fetched on demand
cpSync('fonts', 'dist/fonts', { recursive: true });
cpSync('sound', 'dist/sound', { recursive: true }); // music, fetched once a game is under way
writeFileSync('index.html', standalone); // served by GitHub Pages from the repo root
writeFileSync('sw.js', sw);
console.log('built', (artifact.length / 1024).toFixed(0) + ' KB');
