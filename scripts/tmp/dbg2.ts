import { readFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import pc from 'polygon-clipping';
type P=[number,number];
const inRing = (p: P, r: P[]) => { let c = false; for (let i = 0, j = r.length - 1; i < r.length; j = i++) { const [xi, yi] = r[i], [xj, yj] = r[j]; if ((yi > p[1]) !== (yj > p[1]) && p[0] < ((xj - xi) * (p[1] - yi)) / (yj - yi) + xi) c = !c; } return c; };
const topo = JSON.parse(readFileSync('node_modules/world-atlas/land-50m.json', 'utf8'));
const g: any = (feature(topo, topo.objects.land) as any).features[0].geometry;
const q:P=[-8.4,43.3];
const hits = g.coordinates.map((p:any,i:number)=>[i,inRing(q,p[0]),p[0].length]).filter((x:any)=>x[1]);
console.log(hits);
const eu = g.coordinates[hits[0][0]];
const xs=eu[0].map((q:P)=>q[0]); console.log(Math.min(...xs),Math.max(...xs), eu.length);
const d = pc.difference(eu, [[[-30,-45],[60,-45],[60,11.5],[-30,36],[-30,-45]]]);
console.log(d.length, d.map((p:any)=>p[0].length));
console.log(d.map((p:any)=>inRing(q,p[0])));
