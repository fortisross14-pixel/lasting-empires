"""Merge the 1600/1700 ownership research into src/data/later-owners.ts, with checks.

Usage: python3 scripts/merge-starts.py DIR   (DIR holds in/ and out/ as written by the research brief)
"""
import os, re, sys, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = sys.argv[1]
RELIGIONS = {'catholic', 'protestant', 'orthodox', 'coptic', 'muslim', 'hindu', 'buddhist', 'confucian', 'shinto', 'animist', 'nahuatl', 'inti'}

src = open(os.path.join(ROOT, 'src/data/provinces.ts')).read()
provs = [l.split(';')[0] for l in src.split('\n') if re.match(r'^[a-z_0-9]+;', l) and len(l.split(';')) >= 9]
nsrc = open(os.path.join(ROOT, 'src/data/nations.ts')).read()
known = {l.split(';')[0] for l in nsrc.split('\n') if re.match(r'^[a-z_0-9]+;[^;]+;[^;]+;#', l)} | {'castile', 'portugal', 'aragon', 'natives', 'tribes', 'bedouins'}

def lines(path):
    if not os.path.exists(path): return []
    return [l.strip() for l in open(path).read().split('\n') if l.strip() and not l.startswith('#')]

new_nat = {}
for l in lines(os.path.join(D, 'in/shared_nations.txt')): new_nat[l.split(';')[0]] = l
for f in sorted(glob.glob(os.path.join(D, 'out/*_nations.txt'))):
    for l in lines(f):
        p = l.split(';')
        if len(p) != 10 or not p[3].startswith('#') or p[5] not in RELIGIONS: print('BAD nation', os.path.basename(f), l); continue
        if p[0] in known: print('SKIP nation already in the game', p[0]); continue
        if p[0] in new_nat and new_nat[p[0]] != l: print('DUP nation (first kept)', p[0], os.path.basename(f)); continue
        new_nat[p[0]] = l
ok_owner = known | set(new_nat)

owners = {}
for f in sorted(glob.glob(os.path.join(D, 'out/*.txt'))):
    b = os.path.basename(f)
    if any(b.endswith(x) for x in ('_nations.txt', '_society.txt', '_subjects.txt', '_notes.txt')): continue
    for l in lines(f):
        p = l.split(';')
        if len(p) < 3: print('BAD row', b, l); continue
        pid, a, c = p[0], p[1], p[2]
        for o in (a, c):
            if o not in ok_owner: print('UNKNOWN owner', b, pid, o); a = a if a in ok_owner else 'natives'; c = c if c in ok_owner else 'natives'
        if pid in owners: print('DUP province', pid)
        owners[pid] = (a, c)
missing = [p for p in provs if p not in owners]
extra = [p for p in owners if p not in provs]
print(f'{len(owners)} provinces, {len(missing)} missing, {len(extra)} unknown, {len(new_nat)} new realms')
for m in missing[:30]: print('MISSING', m)
for x in extra[:30]: print('UNKNOWN province', x)

society = []
for f in sorted(glob.glob(os.path.join(D, 'out/*_society.txt'))):
    for l in lines(f):
        p = (l.split(';') + ['', '', ''])[:4]
        if p[0] not in owners: print('society: unknown province', p[0]); continue
        if (p[1] and p[1] not in RELIGIONS) or (p[2] and p[2] not in RELIGIONS): print('society: bad religion', l); continue
        society.append(';'.join(p))
subjects = []
for f in sorted(glob.glob(os.path.join(D, 'out/*_subjects.txt'))):
    for l in lines(f):
        p = l.split(';')
        if len(p) != 3 or p[0] not in ('1600', '1700') or p[1] not in ok_owner or p[2] not in ok_owner: print('subjects: bad', l); continue
        subjects.append(l)

# realms that own no land in either year are not needed
used = {o for a, c in owners.values() for o in (a, c)}
for k in list(new_nat):
    if k not in used: print('drop unused realm', k); del new_nat[k]
for k, l in new_nat.items():
    cap = l.split(';')[6]
    if cap not in owners: print('realm capital not a province', k, cap)

out = ['// Generated by scripts/merge-starts.py from the 1600/1700 research. Do not edit by hand.',
       '// id;owner1600;owner1700', 'export const LATER_TABLE = `',
       *[f'{p};{owners[p][0]};{owners[p][1]}' for p in provs if p in owners], '`;',
       '// realms that appear only in the later starts (nations.ts format)', 'export const LATER_NATIONS = `', *new_nat.values(), '`;',
       '// id;religion1600;religion1700;culture1700 (empty = unchanged)', 'export const LATER_SOCIETY = `', *society, '`;',
       '// year;subject;overlord', 'export const LATER_SUBJECTS = `', *subjects, '`;', '']
open(os.path.join(ROOT, 'src/data/later-owners.ts'), 'w').write('\n'.join(out))
print('written', len(society), 'society rows,', len(subjects), 'subjects')
